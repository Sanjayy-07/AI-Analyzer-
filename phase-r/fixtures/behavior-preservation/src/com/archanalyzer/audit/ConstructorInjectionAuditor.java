package com.archanalyzer.audit;

import java.util.ArrayList;
import java.util.List;

public class ConstructorInjectionAuditor {

    // Simulates the original PaymentService from sample-demo-project
    static class OriginalPaymentService {
        private OriginalNotificationService notificationService;

        public OriginalPaymentService() {
            // In original code, it instantiated NotificationService
            this.notificationService = new OriginalNotificationService();
        }

        public boolean processPayment(String orderId, double amount) {
            // Always sends receipt
            notificationService.sendReceipt(orderId, amount);
            return true;
        }

        public List<String> getDispatchedReceipts() {
            return notificationService.receipts;
        }
    }

    static class OriginalNotificationService {
        public List<String> receipts = new ArrayList<>();
        public void sendReceipt(String orderId, double amount) {
            receipts.add("RECEIPT:" + orderId + ":" + amount);
        }
    }

    // Simulates the refactored PaymentService generated by AstCallerRewriter
    interface INotificationService {
        void sendReceipt(String orderId, double amount);
    }

    static class RefactoredNotificationService implements INotificationService {
        public List<String> receipts = new ArrayList<>();
        @Override
        public void sendReceipt(String orderId, double amount) {
            receipts.add("RECEIPT:" + orderId + ":" + amount);
        }
    }

    static class RefactoredPaymentService {
        private INotificationService notificationService;

        // Generated default constructor with null decoupling
        public RefactoredPaymentService() {
            this.notificationService = null;
        }

        // Generated dependency injection constructor
        public RefactoredPaymentService(INotificationService notificationService) {
            this.notificationService = notificationService;
        }

        // Generated setter injection
        public void setNotificationService(INotificationService notificationService) {
            this.notificationService = notificationService;
        }

        public boolean processPayment(String orderId, double amount) {
            // Generated guarded call by AstCallerRewriter
            if (notificationService != null) {
                notificationService.sendReceipt(orderId, amount);
            }
            return true;
        }

        public INotificationService getNotificationService() {
            return notificationService;
        }
    }

    public static void main(String[] args) {
        System.out.println("=================================================================");
        System.out.println("PHASE R-C: CONSTRUCTOR INJECTION & RUNTIME SAFETY AUDIT");
        System.out.println("=================================================================");

        // TEST A: Existing Constructor Usage (Default Constructor)
        System.out.println("\n[TEST A] Existing Default Constructor Usage (new PaymentService()):");
        OriginalPaymentService origA = new OriginalPaymentService();
        boolean origResultA = origA.processPayment("ORD-1001", 50.0);

        RefactoredPaymentService refA = new RefactoredPaymentService();
        boolean refResultA = refA.processPayment("ORD-1001", 50.0);

        System.out.printf("  Original processPayment() result:   %b, Receipts: %d\n", origResultA, origA.getDispatchedReceipts().size());
        System.out.printf("  Refactored processPayment() result: %b, Receipts: 0 (Field is null!)\n", refResultA);
        System.out.printf("  Is refactored object usable without throwing NPE? %b (guarded by null-check)\n", refResultA);

        // TEST B: Null Dependency Silent Functional Loss
        System.out.println("\n[TEST B] Null Dependency Silent Side-Effect Loss:");
        boolean silentLoss = (origA.getDispatchedReceipts().size() == 1) && (refA.getNotificationService() == null);
        System.out.printf("  Original dispatched receipt: %s\n", origA.getDispatchedReceipts().get(0));
        System.out.printf("  Refactored dispatched receipt: NONE (Silently skipped!)\n");
        System.out.printf("  Finding: Default constructor without injection causes SILENT FUNCTIONALITY LOSS: %b\n", silentLoss);

        // TEST C: Constructor Injection (Explicit Injection)
        System.out.println("\n[TEST C] Constructor Injection (new PaymentService(notificationService)):");
        RefactoredNotificationService notifC = new RefactoredNotificationService();
        RefactoredPaymentService refC = new RefactoredPaymentService(notifC);
        boolean refResultC = refC.processPayment("ORD-1002", 75.0);

        boolean injectionPreserved = refResultC && notifC.receipts.size() == 1;
        System.out.printf("  Refactored with DI result: %b, Receipts: %d\n", refResultC, notifC.receipts.size());
        System.out.printf("  Receipt content: %s\n", notifC.receipts.get(0));
        System.out.printf("  Is behavior preserved under explicit injection? %b\n", injectionPreserved);

        // TEST D: Setter Injection
        System.out.println("\n[TEST D] Setter Injection (setNotificationService(...)):");
        RefactoredPaymentService refD = new RefactoredPaymentService();
        System.out.printf("  Before setter: notificationService = %s\n", refD.getNotificationService());
        RefactoredNotificationService notifD = new RefactoredNotificationService();
        refD.setNotificationService(notifD);
        System.out.printf("  After setter:  notificationService = %s\n", refD.getNotificationService().getClass().getSimpleName());
        refD.processPayment("ORD-1003", 100.0);
        boolean setterPreserved = notifD.receipts.size() == 1;
        System.out.printf("  Receipts after setter: %d (%s)\n", notifD.receipts.size(), notifD.receipts.get(0));
        System.out.printf("  Is behavior preserved after setter injection? %b\n", setterPreserved);

        // TEST E: Dependency Replacement at Runtime
        System.out.println("\n[TEST E] Runtime Dependency Replacement:");
        RefactoredNotificationService notifE1 = new RefactoredNotificationService();
        RefactoredNotificationService notifE2 = new RefactoredNotificationService();
        RefactoredPaymentService refE = new RefactoredPaymentService(notifE1);
        refE.processPayment("ORD-1004", 10.0);
        refE.setNotificationService(notifE2); // swap to mock/secondary
        refE.processPayment("ORD-1005", 20.0);

        boolean swapSuccess = notifE1.receipts.size() == 1 && notifE2.receipts.size() == 1;
        System.out.printf("  Target 1 receipts: %s\n", notifE1.receipts);
        System.out.printf("  Target 2 receipts: %s\n", notifE2.receipts);
        System.out.printf("  Is dynamic replacement successful? %b\n", swapSuccess);

        System.out.println("\n=================================================================");
        System.out.println("VERDICT ON CONSTRUCTOR INJECTION & NULL DECOUPLING:");
        System.out.println("CLASSIFICATION: BEHAVIOR PRESERVING ONLY UNDER EXPLICIT INJECTION");
        System.out.println("WARNING: Uninjected default constructor silently suppresses side-effects!");
        System.out.println("=================================================================");
    }
}
